def hero_frames(h):
    head = h["head"] + h.get("face", FACE)
    idle = [
        head + TORSO + LEGS_IDLE,
        head + TORSO + LEGS_IDLE,
        [BLANK] + head + TORSO + LEGS_IDLE[1:],  # breathe: body sinks a pixel
        [BLANK] + head + TORSO + LEGS_IDLE[1:],
    ]
    run = [
        [BLANK] + head + TORSO_SWING + LEGS_STRIDE,
        head + TORSO + LEGS_PASS,
        [BLANK] + head + TORSO_SWING + LEGS_STRIDE,
        head + TORSO + LEGS_PASS,
    ]
    return idle, run


for hid, h in HEROES.items():
    pal = {**SKIN, **h["pal"]}
    idle, run = hero_frames(h)
    for i, rows in enumerate(idle):
        save_rows(f"hero_{hid}_idle_f{i}", rows, pal)
    for i, rows in enumerate(run):
        # stride frames 0/2 mirror the legs so the run actually alternates
        if i == 2:
            rows = rows[:-6] + [r[::-1] for r in rows[-6:]]
        save_rows(f"hero_{hid}_run_f{i}", rows, pal)

