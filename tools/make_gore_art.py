BLOOD = [(110, 14, 20), (132, 20, 24), (86, 10, 16), (150, 30, 30)]
for i in range(6):  # splats: a core blob, satellite drops, a few runs
    w, h = R.choice([(24, 16), (28, 18), (20, 14), (32, 20)])
    img = new(w, h)
    p = img.load()
    cx, cy = w / 2, h / 2
    for y in range(h):
        for x in range(w):
            d = ((x - cx) / (w * 0.32)) ** 2 + ((y - cy) / (h * 0.32)) ** 2
            n = math.sin(x * 1.3 + i) * 0.18 + math.cos(y * 1.7 - i) * 0.18
            if d < 1 + n:  # dark wet core, brighter rim, rare glints
                col = BLOOD[2] if d < 0.45 else BLOOD[0] if d < 0.85 else BLOOD[1]
                if R.random() < 0.05:
                    col = BLOOD[3]
                p[x, y] = col + (235,)
    for _ in range(14):
        a, r = R.uniform(0, 6.28), R.uniform(0.35, 0.5)
        x, y = int(cx + math.cos(a) * w * r), int(cy + math.sin(a) * h * r)
        if 0 <= x < w and 0 <= y < h:
            p[x, y] = R.choice(BLOOD) + (220,)
            if x + 1 < w:
                p[x + 1, y] = R.choice(BLOOD) + (200,)
    save(img, f"splat_{i}")
for i in range(3):  # streaks: a smear dragged to the right
    w, h = 30, 7
    img = new(w, h)
    p = img.load()
    for x in range(w):
        t = x / w
        half = (1 - t) * 3 + 0.5
        for y in range(h):
            if abs(y - 3 + math.sin(x * 0.4 + i) * 0.6) < half and R.random() > t * 0.5:
                p[x, y] = (BLOOD[2] if abs(y - 3) < half * 0.5 else BLOOD[0]) + (int(230 * (1 - t * 0.6)),)
    save(img, f"streak_{i}")

for i in range(2):  # scorch: soot ring with a darker heart
    s = 44
    img = new(s, 30)
    p = img.load()
    for y in range(30):
        for x in range(s):
            d = math.hypot((x - s / 2) / (s / 2), (y - 15) / 15)
            n = R.random() * 0.25
            if d < 0.95 - n:
                a = int(200 * (1 - d) ** 0.6)
                c = 14 if d < 0.5 else 30
                p[x, y] = (c, c - 4, c - 6, a)
    save(img, f"scorch_{i}")

