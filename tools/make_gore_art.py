# ------------------------------------------------------------------- gore ---
FLESH = [(120, 24, 28), (150, 36, 34), (92, 16, 22)]
SKIN = [(122, 134, 104), (98, 110, 84)]
BONE = (224, 214, 190)


def blob(w, h, cols, holes=0.0, outline=True):
    img = new(w, h)
    p = img.load()
    cx, cy = (w - 1) / 2, (h - 1) / 2
    for y in range(h):
        for x in range(w):
            d = ((x - cx) / (w / 2)) ** 2 + ((y - cy) / (h / 2)) ** 2
            if d < 1 - R.random() * 0.35 and R.random() > holes:
                p[x, y] = R.choice(cols) + (255,)
    if outline:
        edge = []
        for y in range(h):
            for x in range(w):
                if p[x, y][3] == 0 and any(0 <= x + dx < w and 0 <= y + dy < h and p[x + dx, y + dy][3] and p[x + dx, y + dy] != K
                                           for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                    edge.append((x, y))
        for x, y in edge:
            p[x, y] = (40, 8, 12, 255)
    return img


