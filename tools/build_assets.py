#!/usr/bin/env python3
"""Bundle every PNG (and assets/sounds/*.mp3 as window.SOUNDS) in assets/sprites, assets/custom, assets/craftpix and
assets/zombies into src/assets.js as base64 data URIs, so the game runs from
file:// and can be inlined into a single-file build by tools/build_dist.py.
A zombified frame (tools/zombify.py) replaces the same-named original."""
import base64
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT = os.path.join(ROOT, "src", "assets.js")

entries = {}
for sub in ("assets/sprites", "assets/custom", "assets/craftpix", "assets/zombies"):
    d = os.path.join(ROOT, sub)
    for fn in sorted(os.listdir(d)):
        if not fn.endswith(".png"):
            continue
        name = fn[:-4].replace("_anim_f", "_f")
        with open(os.path.join(d, fn), "rb") as f:
            b64 = base64.b64encode(f.read()).decode()
        entries[name] = f'  "{name}": "data:image/png;base64,{b64}"'

sounds = []
sdir = os.path.join(ROOT, "assets", "sounds")
for fn in sorted(os.listdir(sdir)) if os.path.isdir(sdir) else []:
    if fn.endswith(".mp3"):
        with open(os.path.join(sdir, fn), "rb") as f:
            sounds.append(f'  "{fn[:-4]}": "data:audio/mpeg;base64,{base64.b64encode(f.read()).decode()}"')

with open(os.path.join(ROOT, "assets", "credits.json")) as f:
    credits = json.load(f)

with open(OUT, "w") as f:
    f.write("// generated by tools/build_assets.py — do not edit\n")
    f.write("window.ASSETS = {\n" + ",\n".join(entries.values()) + "\n};\n")
    f.write("window.SOUNDS = {\n" + ",\n".join(sounds) + "\n};\n")
    f.write("// source of truth: assets/credits.json\n")
    f.write("window.CREDITS = " + json.dumps(credits, indent=1) + ";\n")
print(f"wrote {OUT} with {len(entries)} sprites, {len(sounds)} sounds + credits")
