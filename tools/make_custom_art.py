px = card.load()
EDGE = (24, 18, 26, 255)
GOLD = (226, 180, 62, 255)
PAPER = (222, 202, 158, 255)
PAPER2 = (206, 184, 138, 255)
for y in range(60):
    for x in range(44):
        if x in (0, 43) or y in (0, 59):
            px[x, y] = EDGE
        elif x in (1, 42) or y in (1, 58):
            px[x, y] = GOLD
        else:
            px[x, y] = PAPER2 if (x + y) % 7 == 0 else PAPER
for cx, cy in ((3, 3), (38, 3), (3, 54), (38, 54)):
    for dx in range(3):
        for dy in range(3):
            if dx + dy < 3:
                px[cx + dx, cy + dy] = GOLD
