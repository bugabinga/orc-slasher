# ------------------------------------------------------------ cave tiles ---
# procedural rock floor/wall tiles, deterministic per variant.
def cave_floor(i):
    random.seed(4200 + i)
    img = Image.new("RGBA", (16, 16))
    px = img.load()
    for y in range(16):
        for x in range(16):
            v = random.random()
            if v < 0.72: c = (68, 59, 55)
            elif v < 0.92: c = (61, 53, 50)
            else: c = (77, 66, 60)
            px[x, y] = (*c, 255)
    for _ in range(2):  # cracks
        cx, cy = random.randint(1, 14), random.randint(1, 14)
        for _ in range(random.randint(3, 6)):
            px[cx, cy] = (38, 32, 32, 255)
            cx = max(0, min(15, cx + random.randint(-1, 1)))
            cy = max(0, min(15, cy + random.randint(-1, 1)))
    for _ in range(random.randint(2, 4)):  # pebbles
        px[random.randint(0, 15), random.randint(0, 15)] = (90, 78, 68, 255)
    img.save(os.path.join(OUT, f"cave_floor_{i}.png"))


def cave_wall(i):
    random.seed(6200 + i)
    img = Image.new("RGBA", (16, 16))
    px = img.load()
    for y in range(16):
        for x in range(16):
            v = random.random()
            if v < 0.75: c = (27, 22, 31)
            elif v < 0.93: c = (23, 19, 27)
            else: c = (36, 30, 42)
            px[x, y] = (*c, 255)
    for _ in range(random.randint(2, 3)):  # jagged highlight veins
        cx, cy = random.randint(1, 14), random.randint(1, 14)
        for _ in range(random.randint(2, 5)):
            px[cx, cy] = (46, 39, 54, 255)
            cx = max(0, min(15, cx + random.randint(-1, 1)))
            cy = max(0, min(15, cy + random.randint(-1, 1)))
    img.save(os.path.join(OUT, f"cave_wall_{i}.png"))


for i in range(4):
    cave_floor(i)
for i in range(2):
    cave_wall(i)

